"""Scenario register (normative source: SCENARIOS.md, AC-321; issue #340).

AC-321: the adapter's parse of a response recorded from the real server equals
the header a human reads off the recording. The fake in `test_cookiecloud.py`
is only trustworthy because this pins it against the real shape
(behavior-first-testing: an unverified fake is a lie that grows more confident).

Provenance, and why there are two recordings, is in
`tests/unit/fixtures/cookiecloud/README.md`.
"""

from __future__ import annotations

import json
from collections.abc import Iterator
from pathlib import Path

import httpx
import pytest

from adapters import cookiecloud as cc

pytestmark = pytest.mark.fixture


@pytest.fixture(autouse=True)
def _clear_cache() -> Iterator[None]:
    """The adapter caches by (base, uuid, domain); two bodies share that key."""
    cc.invalidate()
    yield
    cc.invalidate()


FIXTURES = Path(__file__).resolve().parent / "fixtures" / "cookiecloud"
ZHIHU_ONLY = FIXTURES / "export-zhihu-domain.json"
ALL_DOMAINS = FIXTURES / "export-all-domains.json"

# The uuid and token are not in the recording; the adapter never sends them in
# a way this test inspects, and the value below is synthetic.
CONFIG = cc.Config(
    base_url="https://cookies.example",
    uuid="recorded-uuid",
    admin_token="synthetic-admin-token",
    domain="zhihu.com",
)

# Read off the recording by hand, not generated by the code under test: a
# `zhihu.com` needle returned `.zhihu.com`, `www.zhihu.com` and
# `zhuanlan.zhihu.com`, and the three names scoped to several paths
# (JOID/SESSIONID/osd) keep their `/question/659037399/answer` value.
EXPECTED_ZHIHU_HEADER = (
    "__zse_ck=synthetic-zse-ck-1; _xsrf=synthetic-xsrf-1; _zap=synthetic-zap-1; "
    "d_c0=synthetic-d-c0-1; z_c0=synthetic-z-c0-1; JOID=synthetic-joid-3; "
    "SESSIONID=synthetic-sessionid-2; osd=synthetic-osd-3; q_c1=synthetic-q-c1-1"
)


def _fetch(body: str) -> str:
    def handler(request: httpx.Request) -> httpx.Response:
        return httpx.Response(200, text=body)

    with httpx.Client(transport=httpx.MockTransport(handler)) as client:
        return cc.fetch_cookie_header(client, CONFIG, secure_ok=True)


def test_the_recorded_zhihu_export_parses_to_the_expected_header() -> None:
    assert _fetch(ZHIHU_ONLY.read_text(encoding="utf-8")) == EXPECTED_ZHIHU_HEADER


def test_the_server_filter_matched_subdomains_not_only_the_exact_host() -> None:
    """`domain=zhihu.com` came back with `www.` and `zhuanlan.` too.

    That is the label-suffix rule (`design/protocol.md` §12) as seen from the
    consumer side: the adapter asks, the server filters, and the answer includes
    subdomains. An exact-host filter would have returned neither.
    """
    domains = {
        cookie["domain"]
        for cookie in json.loads(ZHIHU_ONLY.read_text(encoding="utf-8"))
    }
    assert domains == {".zhihu.com", "www.zhihu.com", "zhuanlan.zhihu.com"}


def test_the_adapter_does_not_re_filter_by_domain() -> None:
    """The `domain=` filter is the server's; the adapter passes its answer on.

    Recorded without `domain=`, the same uuid carries `.x.com` cookies. They
    must survive here: re-filtering would be a second label rule to keep in sync
    with the server's, and would drop a cookie the server kept through its
    bucket match. This test is what makes "we trust the server's filter" a
    checked decision instead of a comment.
    """
    header = _fetch(ALL_DOMAINS.read_text(encoding="utf-8"))
    assert "auth_token=synthetic-auth-token-1" in header
    assert "d_c0=synthetic-d-c0-1" in header
